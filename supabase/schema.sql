  false,
  10485760,
  array['image/jpeg', 'image/png', 'image/webp', 'application/pdf']
)
on conflict (id) do update
set public = false,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Teachers upload their TKJ course assets" on storage.objects;
create policy "Teachers upload their TKJ course assets"
  on storage.objects for insert to authenticated
  with check (
    bucket_id = 'tkj-course-assets'
    and (storage.foldername(name))[1] = (select auth.uid())::text
    and (select private.current_role()) = 'teacher'
  );

drop policy if exists "Users read assets for visible TKJ lessons" on storage.objects;
create policy "Users read assets for visible TKJ lessons"
  on storage.objects for select to authenticated
  using (
    bucket_id = 'tkj-course-assets'
    and exists (
      select 1 from public.lesson_attachments as attachment
      join public.lessons as lesson on lesson.id = attachment.lesson_id
      where attachment.storage_path = name
        and (
          attachment.author_id = (select auth.uid())
          or lesson.is_published
        )
    )
  );

drop policy if exists "Visitors read assets for published TKJ lessons" on storage.objects;
create policy "Visitors read assets for published TKJ lessons"
  on storage.objects for select to anon
  using (
    bucket_id = 'tkj-course-assets'
    and exists (
      select 1 from public.lesson_attachments as attachment
      join public.lessons as lesson on lesson.id = attachment.lesson_id
      where attachment.storage_path = name and lesson.is_published
    )
  );

drop policy if exists "Teachers delete their TKJ course assets" on storage.objects;
create policy "Teachers delete their TKJ course assets"
  on storage.objects for delete to authenticated
  using (
    bucket_id = 'tkj-course-assets'
    and (storage.foldername(name))[1] = (select auth.uid())::text
    and (select private.current_role()) = 'teacher'
  );

commit;
